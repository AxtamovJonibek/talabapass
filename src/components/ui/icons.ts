export type IconName = keyof typeof ICONS;

export function isIconName(value: string): value is IconName {
  return value in ICONS;
}

/** O'lcham shkalasi (docs/ikonkalar.md): kichik 16, oddiy 20, katta 24; bundan kattasi — bezak (o'zgarmaydi). */
export const ICON_SCALE = [16, 20, 24] as const;
export function iconSize(size: number): number {
  if (size >= 32) return size;
  return ICON_SCALE.reduce((best, s) => (Math.abs(s - size) < Math.abs(best - size) ? s : best), ICON_SCALE[0]);
}
